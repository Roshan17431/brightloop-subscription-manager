CREATE TABLE tax_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(160) NOT NULL,
  description VARCHAR(1000),
  rate NUMERIC(5,2) NOT NULL CHECK (rate BETWEEN 0 AND 100),
  product_type VARCHAR(80),
  product_id BIGINT REFERENCES products(id),
  is_default BOOLEAN NOT NULL DEFAULT FALSE,
  effective_from DATE,
  effective_until DATE,
  status VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE','INACTIVE')),
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  CHECK (effective_from IS NULL OR effective_until IS NULL OR effective_until >= effective_from)
);
CREATE UNIQUE INDEX idx_tax_rules_name ON tax_rules(lower(name));
CREATE INDEX idx_tax_rules_status_id ON tax_rules(status, id);
CREATE INDEX idx_tax_rules_product ON tax_rules(product_id);

CREATE TABLE discounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  name VARCHAR(160) NOT NULL,
  code VARCHAR(64),
  description VARCHAR(1000),
  type VARCHAR(16) NOT NULL CHECK (type IN ('PERCENTAGE','FIXED')),
  value NUMERIC(14,2) NOT NULL CHECK (value > 0),
  scope VARCHAR(16) NOT NULL CHECK (scope IN ('SUBSCRIPTION','PRODUCT')),
  product_id BIGINT REFERENCES products(id),
  subscription_id BIGINT REFERENCES subscriptions(id),
  minimum_quantity INTEGER CHECK (minimum_quantity IS NULL OR minimum_quantity >= 1),
  minimum_purchase NUMERIC(14,2) CHECK (minimum_purchase IS NULL OR minimum_purchase >= 0),
  valid_from DATE,
  valid_until DATE,
  usage_limit INTEGER CHECK (usage_limit IS NULL OR usage_limit >= 1),
  used_count INTEGER NOT NULL DEFAULT 0 CHECK (used_count >= 0),
  status VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE','INACTIVE')),
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  CHECK (type <> 'PERCENTAGE' OR value <= 100),
  CHECK (valid_from IS NULL OR valid_until IS NULL OR valid_until >= valid_from),
  CHECK (usage_limit IS NULL OR used_count <= usage_limit)
);
CREATE UNIQUE INDEX idx_discounts_name ON discounts(lower(name));
CREATE UNIQUE INDEX idx_discounts_code ON discounts(lower(code)) WHERE code IS NOT NULL;
CREATE INDEX idx_discounts_status_id ON discounts(status, id);
CREATE INDEX idx_discounts_product ON discounts(product_id);
CREATE INDEX idx_discounts_subscription ON discounts(subscription_id);

CREATE TABLE billing_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  idempotency_key VARCHAR(120) NOT NULL UNIQUE,
  billing_date DATE NOT NULL,
  trigger_type VARCHAR(24) NOT NULL CHECK (trigger_type IN ('MANUAL','SCHEDULED','RETRY')),
  triggered_by VARCHAR(254) NOT NULL,
  status VARCHAR(32) NOT NULL CHECK (status IN ('RUNNING','COMPLETED','COMPLETED_WITH_ERRORS','FAILED')),
  total_evaluated INTEGER NOT NULL DEFAULT 0 CHECK (total_evaluated >= 0),
  invoices_generated INTEGER NOT NULL DEFAULT 0 CHECK (invoices_generated >= 0),
  skipped_count INTEGER NOT NULL DEFAULT 0 CHECK (skipped_count >= 0),
  failed_count INTEGER NOT NULL DEFAULT 0 CHECK (failed_count >= 0),
  expired_closed_count INTEGER NOT NULL DEFAULT 0 CHECK (expired_closed_count >= 0),
  started_at TIMESTAMPTZ NOT NULL,
  completed_at TIMESTAMPTZ,
  error_summary VARCHAR(2000),
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_billing_runs_date_id ON billing_runs(billing_date, id DESC);
CREATE INDEX idx_billing_runs_status_id ON billing_runs(status, id DESC);

CREATE TABLE invoices (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  invoice_number VARCHAR(50) NOT NULL UNIQUE,
  subscription_id BIGINT NOT NULL REFERENCES subscriptions(id),
  subscription_number VARCHAR(50) NOT NULL,
  customer_id BIGINT NOT NULL REFERENCES customers(id),
  customer_name VARCHAR(120) NOT NULL,
  customer_email VARCHAR(254) NOT NULL,
  customer_phone VARCHAR(40),
  customer_company VARCHAR(160),
  billing_address VARCHAR(2000),
  plan_id BIGINT NOT NULL REFERENCES plans(id),
  plan_name VARCHAR(160) NOT NULL,
  billing_period VARCHAR(16) NOT NULL CHECK (billing_period IN ('DAILY','WEEKLY','MONTHLY','YEARLY')),
  billing_period_start DATE NOT NULL,
  billing_period_end DATE NOT NULL,
  issue_date DATE NOT NULL,
  due_date DATE NOT NULL,
  payment_terms VARCHAR(1000) NOT NULL,
  state VARCHAR(16) NOT NULL CHECK (state IN ('DRAFT','CONFIRMED','PAID','CANCELLED')),
  subtotal NUMERIC(19,2) NOT NULL CHECK (subtotal >= 0),
  discount_amount NUMERIC(19,2) NOT NULL CHECK (discount_amount >= 0),
  discount_id BIGINT REFERENCES discounts(id),
  discount_name VARCHAR(160),
  tax_amount NUMERIC(19,2) NOT NULL CHECK (tax_amount >= 0),
  total NUMERIC(19,2) NOT NULL CHECK (total >= 0),
  idempotency_key VARCHAR(120) NOT NULL UNIQUE,
  billing_run_id BIGINT REFERENCES billing_runs(id),
  payment_reference VARCHAR(200),
  paid_at TIMESTAMPTZ,
  confirmed_at TIMESTAMPTZ,
  cancelled_at TIMESTAMPTZ,
  sent_at TIMESTAMPTZ,
  notes VARCHAR(2000),
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT uq_invoices_subscription_period UNIQUE (subscription_id, billing_period_start),
  CHECK (billing_period_end >= billing_period_start),
  CHECK (due_date >= issue_date),
  CHECK (state <> 'PAID' OR (payment_reference IS NOT NULL AND paid_at IS NOT NULL))
);
CREATE INDEX idx_invoices_customer_state_id ON invoices(customer_id, state, id DESC);
CREATE INDEX idx_invoices_state_id ON invoices(state, id DESC);
CREATE INDEX idx_invoices_subscription ON invoices(subscription_id);
CREATE INDEX idx_invoices_billing_run ON invoices(billing_run_id);

CREATE TABLE invoice_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id BIGINT NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id),
  variant_id BIGINT REFERENCES product_variants(id),
  product_name VARCHAR(160) NOT NULL,
  variant_name VARCHAR(120),
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 1000000),
  unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price >= 0),
  subtotal NUMERIC(19,2) NOT NULL CHECK (subtotal >= 0),
  discount_amount NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
  discount_id BIGINT REFERENCES discounts(id),
  discount_name VARCHAR(160),
  tax_rate NUMERIC(5,2) NOT NULL CHECK (tax_rate BETWEEN 0 AND 100),
  tax_rule_id BIGINT REFERENCES tax_rules(id),
  tax_rule_name VARCHAR(160),
  tax_amount NUMERIC(19,2) NOT NULL CHECK (tax_amount >= 0),
  amount NUMERIC(19,2) NOT NULL CHECK (amount >= 0)
);
CREATE INDEX idx_invoice_lines_invoice ON invoice_lines(invoice_id);
CREATE INDEX idx_invoice_lines_product ON invoice_lines(product_id);
CREATE INDEX idx_invoice_lines_variant ON invoice_lines(variant_id);

CREATE TABLE billing_run_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  billing_run_id BIGINT NOT NULL REFERENCES billing_runs(id) ON DELETE CASCADE,
  subscription_id BIGINT NOT NULL REFERENCES subscriptions(id),
  subscription_number VARCHAR(50) NOT NULL,
  billing_period_start DATE NOT NULL,
  status VARCHAR(24) NOT NULL CHECK (status IN ('INVOICED','SKIPPED','EXPIRED_CLOSED','FAILED')),
  invoice_id BIGINT REFERENCES invoices(id),
  invoice_number VARCHAR(50),
  attempt_count INTEGER NOT NULL DEFAULT 1 CHECK (attempt_count >= 1),
  message VARCHAR(1000),
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_billing_run_items_run ON billing_run_items(billing_run_id);
CREATE INDEX idx_billing_run_items_subscription ON billing_run_items(subscription_id);
