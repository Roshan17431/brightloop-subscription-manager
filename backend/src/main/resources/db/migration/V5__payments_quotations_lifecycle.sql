-- 3. Payments table
CREATE TABLE payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  payment_reference VARCHAR(100) NOT NULL UNIQUE,
  idempotency_key VARCHAR(120) NOT NULL UNIQUE,
  invoice_id BIGINT NOT NULL REFERENCES invoices(id),
  invoice_number VARCHAR(50) NOT NULL,
  customer_id BIGINT NOT NULL REFERENCES customers(id),
  customer_name VARCHAR(120) NOT NULL,
  method VARCHAR(32) NOT NULL CHECK (method IN ('BANK_TRANSFER','CASH','UPI','CARD','OTHER')),
  amount NUMERIC(19,2) NOT NULL CHECK (amount > 0),
  payment_date DATE NOT NULL,
  status VARCHAR(24) NOT NULL CHECK (status IN ('COMPLETED','REVERSED')),
  note VARCHAR(1000),
  recorded_by VARCHAR(254) NOT NULL,
  reversed_at TIMESTAMPTZ,
  reversed_by VARCHAR(254),
  reversal_reason VARCHAR(500),
  reversal_reference VARCHAR(100) UNIQUE,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  CHECK (status <> 'REVERSED' OR (reversed_at IS NOT NULL AND reversed_by IS NOT NULL))
);
CREATE INDEX idx_payments_invoice ON payments(invoice_id, id DESC);
CREATE INDEX idx_payments_customer ON payments(customer_id, id DESC);
CREATE INDEX idx_payments_date_method ON payments(payment_date DESC, method, id DESC);
CREATE INDEX idx_payments_status ON payments(status, id DESC);

-- 4. Quotation Templates & Lines
CREATE TABLE quotation_templates (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  name VARCHAR(160) NOT NULL,
  description VARCHAR(2000),
  plan_id BIGINT NOT NULL REFERENCES plans(id),
  plan_name VARCHAR(160) NOT NULL,
  validity_days INTEGER NOT NULL CHECK (validity_days BETWEEN 1 AND 3650),
  payment_terms VARCHAR(1000) NOT NULL,
  status VARCHAR(16) NOT NULL CHECK (status IN ('ACTIVE','INACTIVE')),
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE UNIQUE INDEX idx_quotation_templates_name ON quotation_templates(lower(name));
CREATE INDEX idx_quotation_templates_status_id ON quotation_templates(status, id DESC);
CREATE INDEX idx_quotation_templates_plan ON quotation_templates(plan_id);

CREATE TABLE quotation_template_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  template_id BIGINT NOT NULL REFERENCES quotation_templates(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id),
  variant_id BIGINT REFERENCES product_variants(id),
  product_name VARCHAR(160) NOT NULL,
  variant_name VARCHAR(120),
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 1000000),
  unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price >= 0),
  tax_rate NUMERIC(5,2) NOT NULL CHECK (tax_rate BETWEEN 0 AND 100),
  amount NUMERIC(19,2) NOT NULL CHECK (amount >= 0)
);
CREATE INDEX idx_quotation_template_lines_template ON quotation_template_lines(template_id);
CREATE INDEX idx_quotation_template_lines_product ON quotation_template_lines(product_id);

-- 5. Quotations & Lines
CREATE TABLE quotations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version BIGINT NOT NULL DEFAULT 0,
  quotation_number VARCHAR(50) NOT NULL UNIQUE,
  template_id BIGINT REFERENCES quotation_templates(id),
  template_name VARCHAR(160),
  customer_id BIGINT NOT NULL REFERENCES customers(id),
  customer_name VARCHAR(120) NOT NULL,
  plan_id BIGINT NOT NULL REFERENCES plans(id),
  plan_name VARCHAR(160) NOT NULL,
  issue_date DATE NOT NULL,
  valid_until DATE NOT NULL,
  start_date DATE NOT NULL,
  expiry_date DATE NOT NULL,
  payment_terms VARCHAR(1000) NOT NULL,
  state VARCHAR(16) NOT NULL CHECK (state IN ('DRAFT','SENT','CONFIRMED','CONVERTED','EXPIRED','CANCELLED')),
  subtotal NUMERIC(19,2) NOT NULL CHECK (subtotal >= 0),
  tax_amount NUMERIC(19,2) NOT NULL CHECK (tax_amount >= 0),
  total NUMERIC(19,2) NOT NULL CHECK (total >= 0),
  notes VARCHAR(2000),
  converted_subscription_id BIGINT UNIQUE REFERENCES subscriptions(id),
  converted_subscription_number VARCHAR(50),
  confirmed_at TIMESTAMPTZ,
  converted_at TIMESTAMPTZ,
  cancelled_at TIMESTAMPTZ,
  created_by VARCHAR(254) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  CHECK (valid_until >= issue_date),
  CHECK (expiry_date >= start_date),
  CHECK (state <> 'CONVERTED' OR converted_subscription_id IS NOT NULL)
);
CREATE INDEX idx_quotations_customer_state_id ON quotations(customer_id, state, id DESC);
CREATE INDEX idx_quotations_state_id ON quotations(state, id DESC);
CREATE INDEX idx_quotations_template ON quotations(template_id);

CREATE TABLE quotation_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quotation_id BIGINT NOT NULL REFERENCES quotations(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id),
  variant_id BIGINT REFERENCES product_variants(id),
  product_name VARCHAR(160) NOT NULL,
  variant_name VARCHAR(120),
  quantity INTEGER NOT NULL CHECK (quantity BETWEEN 1 AND 1000000),
  unit_price NUMERIC(14,2) NOT NULL CHECK (unit_price >= 0),
  subtotal NUMERIC(19,2) NOT NULL CHECK (subtotal >= 0),
  tax_rate NUMERIC(5,2) NOT NULL CHECK (tax_rate BETWEEN 0 AND 100),
  tax_amount NUMERIC(19,2) NOT NULL CHECK (tax_amount >= 0),
  amount NUMERIC(19,2) NOT NULL CHECK (amount >= 0)
);
CREATE INDEX idx_quotation_lines_quotation ON quotation_lines(quotation_id);
CREATE INDEX idx_quotation_lines_product ON quotation_lines(product_id);

