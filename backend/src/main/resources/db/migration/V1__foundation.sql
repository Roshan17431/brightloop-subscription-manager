CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, role VARCHAR(16) NOT NULL CHECK (role IN ('ADMIN','STAFF','CUSTOMER')),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 CONSTRAINT users_email_normalized CHECK(email=lower(trim(email)))
);
CREATE INDEX idx_users_name ON users(lower(name));
CREATE TABLE customers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT UNIQUE REFERENCES users(id), name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 phone VARCHAR(40), company_name VARCHAR(160), billing_address VARCHAR(2000),
 status VARCHAR(16) NOT NULL CHECK(status IN ('ACTIVE','INACTIVE')),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 CONSTRAINT customers_email_normalized CHECK(email=lower(trim(email)))
);
CREATE INDEX idx_customers_status_id ON customers(status,id);
CREATE INDEX idx_customers_name ON customers(lower(name));
CREATE TABLE products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL, type VARCHAR(80) NOT NULL,
 sales_price NUMERIC(14,2) NOT NULL CHECK(sales_price>=0), cost_price NUMERIC(14,2) NOT NULL CHECK(cost_price>=0),
 notes VARCHAR(4000), status VARCHAR(16) NOT NULL CHECK(status IN ('ACTIVE','INACTIVE')),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_products_status_id ON products(status,id);
CREATE INDEX idx_products_name ON products(lower(name));
CREATE TABLE product_variants (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id BIGINT NOT NULL REFERENCES products(id),
 name VARCHAR(120) NOT NULL, price_adjustment NUMERIC(14,2) NOT NULL
);
CREATE UNIQUE INDEX idx_variant_product_name ON product_variants(product_id,lower(name));
CREATE TABLE plans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL, description VARCHAR(4000), billing_period VARCHAR(16) NOT NULL CHECK(billing_period IN ('DAILY','WEEKLY','MONTHLY','YEARLY')),
 price NUMERIC(14,2) NOT NULL CHECK(price>=0), minimum_quantity INTEGER NOT NULL CHECK(minimum_quantity>=1),
 available_from DATE, available_until DATE,
 automatic_closing BOOLEAN NOT NULL, early_closing_allowed BOOLEAN NOT NULL, pausing_allowed BOOLEAN NOT NULL, renewal_allowed BOOLEAN NOT NULL,
 status VARCHAR(16) NOT NULL CHECK(status IN ('ACTIVE','INACTIVE')),
 created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 CHECK(available_from IS NULL OR available_until IS NULL OR available_until>=available_from)
);
CREATE INDEX idx_plans_status_id ON plans(status,id);
CREATE INDEX idx_plans_name ON plans(lower(name));
CREATE TABLE plan_products (
 plan_id BIGINT NOT NULL REFERENCES plans(id), product_id BIGINT NOT NULL REFERENCES products(id), PRIMARY KEY(plan_id,product_id)
);
CREATE INDEX idx_plan_products_product ON plan_products(product_id);
CREATE TABLE subscriptions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version BIGINT NOT NULL DEFAULT 0, number VARCHAR(50) NOT NULL UNIQUE,
 customer_id BIGINT NOT NULL REFERENCES customers(id), plan_id BIGINT NOT NULL REFERENCES plans(id), plan_name VARCHAR(160) NOT NULL,
 start_date DATE NOT NULL, expiry_date DATE NOT NULL, payment_terms VARCHAR(1000) NOT NULL,
 state VARCHAR(16) NOT NULL CHECK(state IN ('DRAFT','QUOTATION','CONFIRMED','ACTIVE','CLOSED')),
 total NUMERIC(19,2) NOT NULL CHECK(total>=0), created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
 CHECK(expiry_date>=start_date)
);
CREATE INDEX idx_subscriptions_customer_state_id ON subscriptions(customer_id,state,id);
CREATE INDEX idx_subscriptions_state_id ON subscriptions(state,id);
CREATE TABLE subscription_lines (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 subscription_id BIGINT NOT NULL REFERENCES subscriptions(id), product_id BIGINT NOT NULL REFERENCES products(id), variant_id BIGINT REFERENCES product_variants(id),
 product_name VARCHAR(160) NOT NULL, variant_name VARCHAR(120), quantity INTEGER NOT NULL CHECK(quantity BETWEEN 1 AND 1000000),
 unit_price NUMERIC(14,2) NOT NULL CHECK(unit_price>=0), tax_rate NUMERIC(5,2) NOT NULL CHECK(tax_rate BETWEEN 0 AND 100),
 amount NUMERIC(19,2) NOT NULL CHECK(amount>=0)
);
CREATE INDEX idx_subscription_lines_subscription ON subscription_lines(subscription_id);
CREATE INDEX idx_subscription_lines_product ON subscription_lines(product_id);
CREATE INDEX idx_subscription_lines_variant ON subscription_lines(variant_id);
CREATE TABLE password_reset_tokens (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id), token_hash VARCHAR(64) NOT NULL UNIQUE,
 expires_at TIMESTAMPTZ NOT NULL, used_at TIMESTAMPTZ
);
CREATE INDEX idx_password_reset_user ON password_reset_tokens(user_id);
CREATE INDEX idx_password_reset_expiry ON password_reset_tokens(expires_at);
CREATE TABLE audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor VARCHAR(254) NOT NULL, action VARCHAR(80) NOT NULL, entity_type VARCHAR(40) NOT NULL, entity_id BIGINT NOT NULL,
 timestamp TIMESTAMPTZ NOT NULL, metadata VARCHAR(2000) NOT NULL
);
CREATE INDEX idx_audit_entity_time ON audit_logs(entity_type,entity_id,timestamp);
CREATE INDEX idx_audit_timestamp ON audit_logs(timestamp);
CREATE TABLE spring_session (
 primary_id CHAR(36) NOT NULL PRIMARY KEY, session_id CHAR(36) NOT NULL UNIQUE,
 creation_time BIGINT NOT NULL, last_access_time BIGINT NOT NULL, max_inactive_interval INTEGER NOT NULL,
 expiry_time BIGINT NOT NULL, principal_name VARCHAR(100)
);
CREATE INDEX spring_session_ix2 ON spring_session(expiry_time);
CREATE INDEX spring_session_ix3 ON spring_session(principal_name);
CREATE TABLE spring_session_attributes (
 session_primary_id CHAR(36) NOT NULL REFERENCES spring_session(primary_id) ON DELETE CASCADE,
 attribute_name VARCHAR(200) NOT NULL, attribute_bytes BYTEA NOT NULL, PRIMARY KEY(session_primary_id,attribute_name)
);
